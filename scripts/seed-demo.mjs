const items = definitions.map(
  ([
    id,
    name,
    category,
    hex,
    color,
    material,
    fit,
    minTemp,
    maxTemp,
    scenes,
    style,
    rainSafe,
    windproof,
  ]) => ({
    id,
    name,
    category,
    image: `images/${id}.svg`,
    hex,
    color,
    material,
    fit,
    minTemp,
    maxTemp,
    scenes,
    styles: [style],
    rainSafe,
    windproof,
    available: true,
    seasons:
      minTemp < 5 ? ["秋", "冬"] : maxTemp > 32 ? ["春", "夏"] : ["春", "秋"],
    notes:
      material === null
        ? "示例单品，材质待确认；录入实物后补充实际触感与保暖反馈。"
        : "示例单品，属性用于演示；请根据实际衣物调整。",
    compatibleWith: [],
  }),
);
for (const item of items) {
  item.compatibleWith = items
    .filter(
      (other) =>
        item.id !== other.id &&
        item.category !== other.category &&
        item.scenes.some((s) => other.scenes.includes(s)),
    )
    .map((x) => x.id);
  writeFileSync(
    `public/images/${item.id}.svg`,
    drawing(item.category, item.hex, item.id),
  );
}
